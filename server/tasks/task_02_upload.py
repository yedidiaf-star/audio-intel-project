import os # ייבוא ספריית os לעבודה מול מערכת ההפעלה (נתיבים, תיקיות ומחיקת קבצים)
import uuid # ייבוא ספריית uuid ליצירת מזהים ייחודיים ואקראיים עבור שמות הקבצים
from flask import Flask, request, jsonify, render_template # ייבוא רכיבים משימוש בספריית Flask ליצירת שרת ווב, טיפול בבקשות, החזרת JSON ותצוגת תבניות HTML
from pydub import AudioSegment # ייבוא המחלקה AudioSegment מספרית pydub המשמשת לטעינה ועיבוד של קבצי שמע
from pydub.exceptions import CouldntDecodeError # ייבוא שגיאה ספציפית המציינת שקובץ השמע פגום או לא ניתן לפענוח

app = Flask(__name__) # אתחול ויצירת מופע של אפליקציית Flask (שרת הווב) ושמירתו במשתנה app

UPLOAD_FOLDER = 'uploads' # הגדרת שם התיקייה שבה יישמרו הקבצים המועלים על ידי המשתמשים
app.config['MAX_CONTENT_LENGTH'] = 50 * 1024 * 1024  # הגבלת גודל ל-50MB # הגדרת גודל מקסימלי מותר לבקשת HTTP ל-50 מגה-בייט (הכפלת בייטים לקילובייטים ואז למגה-בייטים)
os.makedirs(UPLOAD_FOLDER, exist_ok=True) # יצירת תיקיית ההעלאות במערכת במידה ואינה קיימת (exist_ok=True מונע שגיאה אם התיקייה כבר קיימת)

ALLOWED_EXTENSIONS = {'wav', 'mp3'} # הגדרת קבוצה (Set) המכילה את סיומות הקבצים המותרות להעלאה (WAV ו-MP3 בלבד)

def allowed_file(filename): # הגדרת פונקציה המקבלת שם קובץ ובודקת האם הסיומת שלו חוקית ומותרת להעלאה
    return '.' in filename and filename.rsplit('.', 1)[1].lower() in ALLOWED_EXTENSIONS # החזרת אמת (True) אם יש נקודה בשם הקובץ והסיומת (לאחר המרה לאותיות קטנות) נמצאת ברשימה המותרת

@app.route('/') # הגדרת נתיב (Route) לעמוד הבית של האתר (שורש האתר) בשיטת GET כברירת מחדל
def index(): # הגדרת הפונקציה שתרוץ כאשר משתמש נכנס לעמוד הבית
    return render_template('index.html') # החזרת קובץ ה-HTML המשמש כממשק המשתמש (נטען מתוך תיקיית templates)

@app.route('/upload', methods=['POST']) # הגדרת נתיב (Route) עבור העלאת קבצים ('/upload') המקבל בקשות מסוג POST בלבד
def upload_file(): # הגדרת הפונקציה המטפלת בלוגיקה של קבלת הקובץ, וולידציה ושמירה
    if 'audio_file' not in request.files: # בדיקה האם הבקשה שנשלחה לשרת אינה מכילה את השדה 'audio_file' בתוך רשימת הקבצים
        return jsonify({"success": False, "error": "לא נשלח שדה audio_file בטופס"}), 400 # החזרת תשובת JSON עם הודעת שגיאה וקוד סטטוס 400 (Bad Request)

    file = request.files['audio_file'] # שמירת אובייקט הקובץ שנשלח מהטופס במשתנה מקומי לצורך עבודה נוחה איתו

    if file.filename == '': # בדיקה האם שם הקובץ ריק (מצב המתרחש כשנשלח טופס מבלי שנבחר קובץ בפועל)
        return jsonify({"success": False, "error": "לא נבחר קובץ"}), 400 # החזרת תשובת JSON עם הודעת שגיאה מתאימה וקוד סטטוס 400

    file.seek(0, os.SEEK_END) # הזזת סמן הקריאה (pointer) אל סוף הקובץ כדי לבדוק מהו האורך (הגודל) שלו בבייטים
    if file.tell() == 0: # בדיקה האם המיקום הנוכחי של הסמן הוא 0, מה שמעיד על כך שהקובץ ריק לחלוטין מתוכן
        return jsonify({"success": False, "error": "הקובץ ריק (0 בייטים)"}), 400 # החזרת שגיאה בפורמט JSON המציינת שהקובץ ריק עם קוד סטטוס 400
    file.seek(0) # החזרת סמן הקריאה לתחילת הקובץ (מיקום 0) כדי שיהיה ניתן לקרוא ולשמור אותו כהלכה בהמשך

    if not allowed_file(file.filename): # בדיקה באמצעות הפונקציה שיצרנו האם סיומת הקובץ אינה תואמת לפורמטים המותרים
        return jsonify({"success": False, "error": "פורמט קובץ לא נתמך. יש להעלות WAV או MP3 בלבד"}), 400 # החזרת שגיאה המציינת שהפורמט אינו נתמך יחד עם קוד סטטוס 400

    file_id = uuid.uuid4().hex # יצירת מזהה אקראי ייחודי (במחרוזת הקסדצימלית) שמשמש כשם קובץ חדש למניעת התנגשויות שמות
    extension = file.filename.rsplit('.', 1)[1].lower() # חילץ סיומת הקובץ המקורית (אחרי הנקודה האחרונה) והמרתה לאותיות קטנות
    new_filename = f"{file_id}.{extension}" # הרכבת שם הקובץ החדש המורכב מהמזהה הייחודי ומסיומת הקובץ המקורית
    filepath = os.path.join(UPLOAD_FOLDER, new_filename) # יצירת הנתיב המלא לשמירת הקובץ על ידי חיבור תיקיית ההעלאות ושם הקובץ החדש
    file.save(filepath) # שמירת קובץ השמע פיזית על הדיסק בשרת בנתיב שהוגדר

    try: # פתיחת בלוק try לביצוע בדיקת תקינות (וולידציה) של תוכן קובץ השמע שעשויה לזרוק שגיאות
        AudioSegment.from_file(filepath) # ניסיון לטעון ולפענח את קובץ השמע באמצעות pydub כדי לוודא שאינו פגום ושזהו באמת קובץ אודיו
    except (CouldntDecodeError, Exception): # לכידת שגיאות פענוח (CouldntDecodeError) או כל שגיאה כללית אחרת במידה והקובץ פגום/מזויף
        os.remove(filepath) # מחיקת הקובץ הפגום מהדיסק בשרת כדי למנוע שמירת קבצים לא תקינים או מסוכנים
        return jsonify({"success": False, "error": "הקובץ פגום ולא ניתן לקריאה כקובץ שמע תקין"}), 400 # החזרת הודעת שגיאה ב-JSON וקוד 400 לאחר מחיקת הקובץ

    return jsonify({ # החזרת תשובת JSON מוצלחת ללקוח (במידה וכל הבדיקות עברו בהצלחה)
        "success": True, # ציון סטטוס הצלחה (True) עבור הצד של הלקוח
        "file_id": file_id, # החזרת המזהה הייחודי שהוקצה לקובץ לצורך שימוש עתידי או תצוגה
        "original_filename": file.filename # החזרת שם הקובץ המקורי כפי שהועלה על ידי המשתמש
    }), 200 # ציון קוד סטטוס HTTP של 200 (OK), המעיד על הצלחת הבקשה והטיפול בה

if __name__ == '__main__': # בדיקה האם הקובץ מורץ ישירות (ולא מיובא כמודול בקובץ אחר)
    app.run(debug=True) # הפעלת שרת הפיתוח של Flask עם מצב debug דולק, המאפשר ריענון אוטומטי והצגת שגיאות מפורטות